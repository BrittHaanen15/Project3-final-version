PenningTrap::PenningTrap(double mag, double pot, double d, bool particle_interactions, Eigen::Vector3d amp_freq)
{
    //Assign member variables from the given inputs
    mag_ = mag;
    pot_ = pot; //pass V_0, can adapt time-wise from there
    d_ = d;
    //Initialise particle vector
    std::vector<Particle> particles_;
    //pass true or false for including particle interactions, default is yes
    particle_interactions_ = particle_interactions;
    //pass amplitude and frequency for time-dependent potential
    //default is zero, i.e. a static field
    amp_freq_ = amp_freq;
}

//Function to append a particle to the vector of particles
void PenningTrap::add_particle(Particle p_in)
{
    particles_.push_back(p_in);
}

