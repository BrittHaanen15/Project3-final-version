//External electric field at location r
//According to equation -nabla(V0)
Eigen::Vector3d PenningTrap::external_E_field(Eigen::Vector3d r, double tt)
{   
    //Corresponds to the V given in the project description
    Eigen::Vector3d E_external(r[0], r[1], -2*r[2]);
    //Update potential acc to time step
    double total_pot = pot_*(1 + amp_freq_[0]*std::cos(amp_freq_[1]*tt));
    //Multiply by the potential/dsquared constant
    E_external = (total_pot/(d_*d_))*E_external;

    return E_external;
}

//External magnetic field at location r
//Simple: mag field was specified as (0,0,B0)
Eigen::Vector3d PenningTrap::external_B_field(Eigen::Vector3d r)
{
    return Eigen::Vector3d(0, 0, mag_);
}

//Force on particle i from particle j
//Calculate with coulomb formula k*(qiqj/|rij|^3)hat(rij)
Eigen::Vector3d PenningTrap::force_particle(int i, int j)
{   
    //Access specified particles
    Particle p_i = particles_[i];
    Particle p_j = particles_[j];

    //Calculate rij, modulus, unit vector
    Eigen::Vector3d r_ij = p_i.r_ - p_j.r_;
    double r_modulus = r_ij.norm();

    //Calculate outcome
    Eigen::Vector3d Coulomb_force = ((p_i.q_*p_j.q_)/(r_modulus*r_modulus*r_modulus))*r_ij;
    Coulomb_force = (1.38935333e5)*Coulomb_force;

    return Coulomb_force;
}

//Calculate total force on particle i from external fields
//This is the Lorentz force, F=qE + qv x B
Eigen::Vector3d PenningTrap::total_force_external(int i, double tt)
{
    //Isolate our particle i
    Particle p_i = particles_[i];

    //check if particle is in trap
    double r = std::sqrt((p_i.r_[0]*p_i.r_[0]) + (p_i.r_[1]*p_i.r_[1]) + (p_i.r_[2]*p_i.r_[2]));

    Eigen::Vector3d total_external_force = Eigen::Vector3d::Zero();

    if (r>d_)
    {
        //Particle outside of trap!
        //Do nothing
    }
    else
    {
        //Particle is in trap!
        //First establish external fields from our functions
        Eigen::Vector3d E = PenningTrap::external_E_field(p_i.r_, tt);
        Eigen::Vector3d B = PenningTrap::external_B_field(p_i.r_);
        //Calculate total acc to Lorentz law
        total_external_force = p_i.q_*E + p_i.q_*(p_i.v_.cross(B));
    }

    return total_external_force;
}

//Calculate the total force on particle i from all the other particles
//The logic is to loop through all the other particles and use the function above 
Eigen::Vector3d PenningTrap::total_force_particles(int i)
{
    Eigen::Vector3d total_particle_force = Eigen::Vector3d::Zero();

    for (int j=0; j < static_cast<int>(particles_.size()); j++)
    {
        if (j != i) 
        {
            total_particle_force = total_particle_force + PenningTrap::force_particle(i, j);
        }       
    }

    return total_particle_force;
}


// The total force on particle i from both external fields and other particles
// This is just adding the total external force + the total internal force
Eigen::Vector3d PenningTrap::total_force(int i, double tt)
{
    Eigen::Vector3d total_force_final = PenningTrap::total_force_external(i, tt);
    if (particle_interactions_ == true)
    {
        //Add particle interactions
        total_force_final += PenningTrap::total_force_particles(i);
    }
    
    return total_force_final;
}



//Evolve system forward one forward Euler step
void PenningTrap::evolve_forward_Euler(double dt, double tt)
{
    //Make copy
    std::vector<Particle> particles_COPY = particles_;

    //Calculate k
    std::vector<Eigen::Vector3d> k_r;
    std::vector<Eigen::Vector3d> k_v;

    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    { 
        Particle p = particles_.at(i);

        //compute k for position using velocity
        k_r.push_back(dt*p.v_);

        //compute k for velocity using acceleration
        Eigen::Vector3d a = (PenningTrap::total_force(i, tt))/particles_COPY[i].m_;
        k_v.push_back(dt*a);

        //update position and velocity
        particles_COPY[i].r_ += k_r[i];
        particles_COPY[i].v_ += k_v[i];
    }

    //Final step
    particles_ = particles_COPY;
}

// Evolve the system one time step (dt) using Runge-Kutta 4th order
void PenningTrap::evolve_RK4(double dt, double tt)
{
    //Make copy
    std::vector<Particle> particles_COPY = particles_;

    //So with this setup, I will treat particles_COPY as the initial state, and particles_ as the temporary state that I can overwrite as we go

    //The first RK step
    //Initialise k
    std::vector<Eigen::Vector3d> k_r_1;
    std::vector<Eigen::Vector3d> k_v_1;

    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {
        /////First step/////
        //compute k1 for position using velocity
        k_r_1.push_back(dt*particles_COPY[i].v_);

        //compute k1 for velocity using acceleration
        Eigen::Vector3d a = (PenningTrap::total_force(i, tt))/particles_COPY[i].m_;
        k_v_1.push_back(dt*a);
    }

    //update
    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {
        //update position and velocity, original + 0.5k
        particles_[i].r_ = particles_COPY[i].r_ + 0.5*k_r_1[i];
        particles_[i].v_ = particles_COPY[i].v_ + 0.5*k_v_1[i];
    }


    //The second RK step
    //Initialise k
    std::vector<Eigen::Vector3d> k_r_2;
    std::vector<Eigen::Vector3d> k_v_2;

    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {
        /////Second step/////
        //compute k2 for position using velocity
        k_r_2.push_back(dt*particles_[i].v_);

        //compute k2 for velocity using acceleration
        Eigen::Vector3d a = (PenningTrap::total_force(i, tt+0.5*dt))/particles_[i].m_;
        k_v_2.push_back(dt*a);
    }

    //update
    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {
        //update position and velocity, original + 0.5k
        particles_[i].r_ = particles_COPY[i].r_ + 0.5*k_r_2[i];
        particles_[i].v_ = particles_COPY[i].v_ + 0.5*k_v_2[i];
    }

    //The third RK step
    //Initialise k
    std::vector<Eigen::Vector3d> k_r_3;
    std::vector<Eigen::Vector3d> k_v_3;

    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {
        /////Third step/////
        //compute k3 for position using velocity
        k_r_3.push_back(dt*particles_[i].v_);

        //compute k3 for velocity using acceleration
        Eigen::Vector3d a = (PenningTrap::total_force(i, tt+0.5*dt))/particles_[i].m_;
        k_v_3.push_back(dt*a);
    }

    //update
    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {
        //update position and velocity, original + 0.5k
        particles_[i].r_ = particles_COPY[i].r_ + k_r_3[i];
        particles_[i].v_ = particles_COPY[i].v_ + k_v_3[i];
    }

    //The fourth RK step
    //Initialise k
    std::vector<Eigen::Vector3d> k_r_4;
    std::vector<Eigen::Vector3d> k_v_4;

    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {           
        /////Fourth step/////
        //compute k4 for position using velocity
        k_r_4.push_back(dt*particles_[i].v_);

        //compute k4 for velocity using acceleration
        Eigen::Vector3d a = (PenningTrap::total_force(i, tt+dt))/particles_[i].m_;
        k_v_4.push_back(dt*a);
    }

    //Final step
    for (int i=0; i < static_cast<int>(particles_COPY.size()); i++)
    {
        particles_[i].r_ = particles_COPY[i].r_ + (1.0/6.0)*(k_r_1[i] + 2*k_r_2[i] + 2*k_r_3[i] + k_r_4[i]);
        particles_[i].v_ = particles_COPY[i].v_ + (1.0/6.0)*(k_v_1[i] + 2*k_v_2[i] + 2*k_v_3[i] + k_v_4[i]);
    }

}


//Count number of particles in the trap
int PenningTrap::count_particles()
  {
    int particle_amount = 0;
    for (int i=0; i < static_cast<int>(particles_.size()); i++)
    {
        //Isolate our particle i
        Particle p_i = particles_[i];

        //check if particle is in trap
        double r = std::sqrt((p_i.r_[0]*p_i.r_[0]) + (p_i.r_[1]*p_i.r_[1]) + (p_i.r_[2]*p_i.r_[2]));

        if (r>d_)
        {
            //Particle outside of trap!
            //Do nothing
        }
        else
        {
            //Particle is in trap!
            //Add to count
            particle_amount += 1;
        }
    }
    return particle_amount;
  }